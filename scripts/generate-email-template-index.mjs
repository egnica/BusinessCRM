import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "..");
const templateDir = path.join(repoRoot, "lib", "emailTemplates");
const indexPath = path.join(templateDir, "index.js");

const files = (await fs.readdir(templateDir))
  .filter(
    (file) =>
      file !== "index.js" &&
      !file.startsWith("_") &&
      /\.(?:js|jsx|mjs)$/.test(file),
  )
  .sort((a, b) => a.localeCompare(b));

if (files.length === 0) {
  throw new Error("No email template files found in lib/emailTemplates.");
}

const imports = files
  .map((file, index) => {
    const extension = path.extname(file);
    const base = file.slice(0, -extension.length);
    return `import template${index} from ${JSON.stringify(`./${base}`)};`;
  })
  .join("\n");

const templateRefs = files.map((_, index) => `template${index}`).join(", ");

const output = `// AUTO-GENERATED by scripts/generate-email-template-index.mjs.
// Add or remove template files in lib/emailTemplates and restart/build the app.
// Do not edit this file manually.

${imports}

const templates = [${templateRefs}];

export function getEmailTemplates() {
  return templates;
}

export function getEmailTemplate(id) {
  return templates.find((template) => template.id === id) || null;
}
`;

await fs.writeFile(indexPath, output, "utf8");

console.log(
  `Registered ${files.length} email template${files.length === 1 ? "" : "s"}: ${files.join(", ")}`,
);
